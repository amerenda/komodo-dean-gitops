global:
  resolve_timeout: 5m

route:
  receiver: 'pushover'
  group_by: ['alertname', 'stack']
  group_wait: 30s
  group_interval: 5m
  repeat_interval: 6h
  routes:
    - matchers:
        - alertname =~ "DiskSpace.*"
      receiver: 'pushover-disk'

receivers:
  - name: 'pushover'
    pushover_configs:
      - user_key: '${PUSHOVER_USER_KEY}'
        token: '${PUSHOVER_TOKEN}'
        title: '[{{ .Status | toUpper }}] {{ .CommonLabels.alertname }} ({{ .CommonLabels.severity }}){{ if gt (len .Alerts) 1 }} x{{ len .Alerts }}{{ end }}'
        message: |-
          {{ range .Alerts }}{{ .Annotations.summary }}
          {{ end }}
        url: 'https://alertmanager.amer.dev'
        priority: '0'
        send_resolved: true
  - name: 'pushover-disk'
    pushover_configs:
      - user_key: '${PUSHOVER_USER_KEY}'
        token: '${PUSHOVER_TOKEN}'
        title: '[{{ .Status | toUpper }}] {{ .CommonLabels.alertname }} ({{ .CommonLabels.severity }}){{ if gt (len .Alerts) 1 }} x{{ len .Alerts }}{{ end }}'
        message: |-
          {{ range .Alerts }}{{ .Annotations.summary }}
          {{ end }}
        url: 'https://grafana.amer.dev/d/infra-node-exporter/infra3a-node-exporter?var-instance={{ (index .Alerts 0).Labels.instance }}'
        priority: '0'
        send_resolved: true
ALERTMANAGER_EOF
    mv "$MON_DIR/alertmanager.yml.tmp" "$MON_DIR/alertmanager.yml"
    chmod 0600 "$MON_DIR/alertmanager.yml"
    chown "$OWNER" "$MON_DIR/alertmanager.yml" 2>/dev/null || true
    # Reload alertmanager so it picks up the new receiver. The mv above is atomic
    # on the host, but OrbStack's virtiofs bridge has been observed taking up to
    # ~60s to propagate a host-side file change into the container's bind-mounted
    # view — a single attempt landing in that window fails with "no such file or
    # directory", so retry with a budget that covers the observed worst case.
    RELOADED=false
    for i in $(seq 1 18); do
        if curl -sf -X POST http://localhost:9093/-/reload >/dev/null 2>&1; then
            RELOADED=true
            break
        fi
        sleep 5
    done
    if "$RELOADED"; then
        log "alertmanager reloaded with Pushover receiver"
    else
        log "WARN: alertmanager reload failed after retries (may not be running yet)"
    fi
else
    log "WARN: failed to fetch Pushover credentials — alertmanager.yml left as no-op"
    ERRORS=$((ERRORS + 1))
fi

# ── Update Komodo git provider PAT ──────────────────────────────────────────

log "Updating Komodo git provider PAT..."
# Use || true on cat so a missing file doesn't kill the script under set -e
ADMIN_PASS=$(cat "$COMPOSE_DIR/komodo/secrets/komodo-dean-admin-password" 2>/dev/null || true)
GITOPS_PAT=$(cat "$RUNNER_SECRETS_DIR/github-pat-k3s-dean-gitops" 2>/dev/null || true)

if [[ -n "$ADMIN_PASS" ]] && [[ -n "$GITOPS_PAT" ]]; then
    # Wait for Komodo to be reachable (may not be up yet at boot)
    KOMODO_UP=false
    for i in $(seq 1 30); do
        if curl -sf http://localhost:9120 >/dev/null 2>&1; then
            KOMODO_UP=true
            break
        fi
        sleep 2
    done

    if "$KOMODO_UP"; then
        # Komodo v2 API: POST /auth/login with {"type":"LoginLocalUser","params":{...}}
        # Use || JWT="" so a failed login doesn't kill the script under set -eo pipefail.
        JWT=$(curl -sf -X POST http://localhost:9120/auth/login \
            -H 'Content-Type: application/json' \
            -d "{\"type\":\"LoginLocalUser\",\"params\":{\"username\":\"admin\",\"password\":\"${ADMIN_PASS}\"}}" \
            2>/dev/null | /opt/homebrew/bin/jq -r '.data.jwt' 2>/dev/null) || JWT=""

        if [[ -n "$JWT" ]] && [[ "$JWT" != "null" ]]; then
            # Komodo v2 API: POST /read with {"type":"...","params":{}}
            PROVIDER_ID=$(curl -sf -X POST http://localhost:9120/read \
                -H 'Content-Type: application/json' \
                -H "Authorization: Bearer ${JWT}" \
                -d '{"type":"ListGitProviderAccounts","params":{}}' 2>/dev/null \
                | /opt/homebrew/bin/jq -r '.[0]._id["$oid"] // empty' 2>/dev/null) || PROVIDER_ID=""

            if [[ -n "$PROVIDER_ID" ]]; then
                # Komodo v2 API: POST /write with {"type":"...","params":{...}}
                curl -sf -X POST http://localhost:9120/write \
                    -H 'Content-Type: application/json' \
                    -H "Authorization: Bearer ${JWT}" \
                    -d "{\"type\":\"UpdateGitProviderAccount\",\"params\":{\"id\":\"${PROVIDER_ID}\",\"account\":{\"domain\":\"github.com\",\"https\":true,\"username\":\"amerenda\",\"token\":\"${GITOPS_PAT}\"}}}" \
                    >/dev/null 2>&1 && log "Komodo git provider PAT updated." \
                    || log "WARN: failed to update Komodo git provider PAT"
            else
                log "No git provider account found in Komodo, skipping PAT update"
            fi
        else
            log "WARN: failed to authenticate with Komodo API"
        fi
    else
        log "Komodo not reachable after 60s, skipping PAT update (will sync on next run)"
    fi
else
    log "WARN: missing admin password or PAT, skipping Komodo PAT update"
fi

# ── Done ────────────────────────────────────────────────────────────────────

if [[ "$ERRORS" -gt 0 ]]; then
    log "Completed with $ERRORS error(s)"
    exit 1
else
    log "All secrets injected successfully."
fi
